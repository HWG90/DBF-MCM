function B.skull(x,y,width,ink,negative,emit)
    local unit=width/80
    for row,line in ipairs(skull_pixels)do
        local column=1
        while column<=80 do
            if line:sub(column,column)=='1'then
                local first=column
                while column<=80 and line:sub(column,column)=='1'do column=column+1 end
                local left,right=x+(first-1)*unit,x+(column-1)*unit
                local bottom,top=y+(30-row)*unit,y+(31-row)*unit
                emit({left,bottom,right,bottom,right,top},ink,'emblem')
                emit({left,bottom,right,top,left,top},ink,'emblem')
            else column=column+1 end
        end
    end
end
function B.hazards(x,y,width,height,ink,emit)
    -- Clip each parallelogram analytically, so neither triangles nor hit areas escape.
    local pitch=math.max(18,height*2.8);local stripe=math.max(7,height*1.1)
    for start=-height,width,pitch do
        local points={{start,y},{start+stripe,y},{start+stripe+height,y+height},{start+height,y+height}}
        local function clip(source,edge,keep)
            local result={}
            for index,p in ipairs(source)do
                local q=source[index%#source+1];local a,b=keep(p[1],edge),keep(q[1],edge)
                if a then result[#result+1]=p end
                if a~=b then local f=(edge-p[1])/(q[1]-p[1]);result[#result+1]={edge,p[2]+f*(q[2]-p[2])}end
            end
            return result
        end
        points=clip(points,0,function(v,e)return v>=e end)
        if #points>0 then points=clip(points,width,function(v,e)return v<=e end)end
        for _,p in ipairs(points)do p[1]=p[1]+x end
        if #points>=3 then polygon(points,ink,emit,'hazard')end
    end
end
return B
